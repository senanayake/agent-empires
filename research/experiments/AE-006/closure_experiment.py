"""Authored AE-002 decision slices; no payment-outcome or belief-update engine.

Run from repository root. --verify-against compares regenerated bytes in memory
without writing reviewed files. --output-dir refuses existing outputs.
"""

import argparse
from dataclasses import asdict
from hashlib import sha256
import json
from pathlib import Path
import platform
import sys

from agent_empires.simulation.actors import Actor
from agent_empires.simulation.decisions import (
    AuthorityGrant, AuthorityRegistry, CapabilityProfile, DecisionQuestion, Decisions, EvidenceUse,
)
from agent_empires.simulation.events import EventHistory
from agent_empires.simulation.knowledge import HolderRef, KnowledgeHolding, KnowledgeItem, KnowledgeStore
from agent_empires.simulation.metrics import decision_metrics


class Case:
    def __init__(self, name, topic, options, kind):
        self.history = EventHistory(name)
        self.store = KnowledgeStore(self.history, [Actor("worker", kind, "team"), Actor("owner", "human", "team")])
        self.authority = AuthorityRegistry(self.store, self.history)
        self.decisions = Decisions(self.store, self.authority, self.history)
        self.question = DecisionQuestion(name, topic, "work-item", options)
        self.decisions.register(self.question)
        self.steps = []
        self.tick = 0

    def step(self, label):
        self.steps.append({"label": label, "through_sequence": len(self.history.events) - 1,
                           "metrics": asdict(decision_metrics(self.history)),
                           "worker_holding_ids": [e.holding.holding_id for e in self.store.view_for("worker").entries]})
        self.tick += 1

    def command(self, label):
        return dict(tick=self.tick, command_id=label, correlation_id=self.question.decision_id)

    def claim(self, name, content, sources, actor="worker", freshness="current"):
        item = KnowledgeItem(name, 1, self.question.topic, content)
        self.store.register_item(item)
        self.store.record_holding(KnowledgeHolding(name, item.ref, HolderRef("actor", actor),
                                                  sources, "high", freshness), **self.command(f"holding-{name}"))

    def grant(self, name, options, actor="worker", basis="explicit_authorization", can_delegate=False):
        self.authority.add_root(AuthorityGrant(name, actor, self.question.scope, options,
                                              can_delegate=can_delegate, basis=basis), **self.command(f"grant-{name}"))

    def select(self, option, label, **changes):
        args = dict(actor_id="worker", expected_version=len(self.decisions.versions(self.question.decision_id)),
                    confidence="high", reason=label, **self.command(label))
        args.update(changes)
        version = self.decisions.select(self.question.decision_id, option, **args)
        self.step(label)
        return version

    def reject(self, label, callback):
        before = self.history.canonical_bytes()
        try:
            callback()
        except ValueError as exc:
            assert before == self.history.canonical_bytes()
            self.steps.append({"label": label, "rejected": str(exc), "history_unchanged": True})
        else:
            raise AssertionError(f"{label} should have failed")

    def result(self, limitation):
        return {"question": asdict(self.question), "steps": self.steps,
                "metrics": asdict(decision_metrics(self.history)),
                "versions": [asdict(v) for v in self.decisions.versions(self.question.decision_id)],
                "history": [e.as_dict() for e in self.history.events], "limitation": limitation}


def use(holding, subject, option, stance="supports", method="observation"):
    return EvidenceUse(holding, subject, option, stance, method, "usable")


def run_cases(kind="agent"):
    results = {}
    c = Case("T1", "idempotency", ("stable", "new"), kind)
    c.claim("private-contract", "stable", ("interface",), actor="owner")
    c.step("contract unavailable to worker")
    v1 = c.decisions.infer("T1", "worker", CapabilityProfile(("new", "stable"), confidence="high"),
                           expected_version=0, missing_information=("interface rationale",), **c.command("infer"))
    c.step("unsupported high-confidence selection")
    assert decision_metrics(c.history).evidence_backed_information_gain == 0
    c.claim("copied-tests", "passes new-key implementation spec", v1.source_ids)
    v2 = c.select("new", "green verification", evidence=(use("copied-tests", v1.ref, "new", method="verification"),))
    assert v2.support == "weak"
    c.claim("duplicate-sample", "authored observed duplicate", ("independent-monitor",))
    c.grant("interface-authority", c.question.alternatives)
    c.select("stable", "explicit precaution after observation", grant_id="interface-authority", confidence="low",
             evidence=(use("duplicate-sample", v1.ref, "new", "challenges"),))
    results["T1"] = c.result("Verification and duplicate sample are authored holdings, not executed implementation checks or payment outcomes. Ruling out new does not establish universal stable-key fitness.")

    c = Case("T2", "retry_count", ("none", "one", "three"), kind)
    c.grant("root", c.question.alternatives, actor="owner", can_delegate=True)
    c.step("root grant without world knowledge")
    c.authority.delegate("delegated", "root", "owner", "worker", options=("none", "one"), **c.command("delegate"))
    c.step("delegation without world knowledge")
    c.select("one", "delegated unsupported choice", grant_id="delegated")
    c.reject("option outside grant", lambda: c.select("three", "out-of-scope", grant_id="delegated"))
    c.authority.revoke("delegated", **c.command("revoke"))
    c.step("revoked for future actions")
    c.reject("revoked grant", lambda: c.select("one", "revoked", grant_id="delegated"))
    c.select("one", "explicit unsupported revision")
    assert decision_metrics(c.history).evidence_backed_information_gain == 0
    results["T2"] = c.result("Authoritative permission is evaluated at command time. Communication of actors' possibly stale beliefs about permission remains separate future work.")

    c = Case("T3", "declines", ("no_declines", "soft", "all"), kind)
    c.grant("policy1", ("no_declines",), basis="policy_constraint")
    v1 = c.select("no_declines", "authorized policy without fitness evidence", grant_id="policy1")
    c.claim("trial-observation", "authored matched soft-class trial challenges blanket policy", ("trial",))
    obs = use("trial-observation", v1.ref, "no_declines", "challenges")
    v2 = c.select("no_declines", "authorized policy challenged", grant_id="policy1", evidence=(obs,))
    assert v2.authority_basis == "policy_constraint" and v2.support == "challenged"
    c.reject("old policy cannot authorize soft", lambda: c.select("soft", "invalid-policy", grant_id="policy1"))
    c.authority.revoke("policy1", **c.command("retire-policy"))
    c.grant("policy2", ("soft",), basis="policy_constraint")
    c.select("soft", "explicitly changed policy authorization", grant_id="policy2", confidence="low", evidence=(obs,))
    assert c.decisions.version("T3", 1) == v1
    results["T3"] = c.result("Trial result and changed policy grant are authored external inputs. No trial deployment, causal outcome engine, empirical trial safety, policy enactment or belief-revision implementation is claimed.")

    c = Case("T4", "idempotency", ("stable", "new"), kind)
    c.grant("architect", c.question.alternatives)
    c.claim("report1", "new", ("vendor-note",))
    c.claim("report2", "new", ("vendor-note",))
    refs = tuple(use(name, c.question.ref, "new", method="report") for name in ("report1", "report2"))
    v1 = c.select("new", "two reports one dependency", grant_id="architect", evidence=refs)
    assert decision_metrics(c.history).evidence_backed_information_gain == 1
    c.claim("trace", "new-key duplicates", ("monitor",))
    refs += (use("trace", v1.ref, "new", "challenges"),)
    c.select("new", "conflict with high confidence", grant_id="architect", evidence=refs)
    v3 = c.select("stable", "precaution retains conflict", grant_id="architect", confidence="low", evidence=refs)
    assert v3.support == "conflicted"
    results["T4"] = c.result("Distinct declared roots are not authenticated independent sources. Conflict is retained, without majority voting or inferred truth.")

    c = Case("T5", "retry_count", ("none", "one", "three"), kind)
    v1 = c.select("three", "unsupported cap")
    c.claim("limited-window", "authored benign first-retry recovery, no comparison of caps one and three", ("window",))
    v2 = c.select("three", "limited observation leaves authority and comparison open",
                  evidence=(use("limited-window", v1.ref, "three", "inconclusive"),))
    assert v2.support == "inconclusive" and v2.authority_basis == "inferred_without_authority"
    results["T5"] = c.result("Benign exposure is an authored observation. Absence of an IncidentOccurred event is not a simulated no-harm or safety result; AE-010 owns world outcomes.")
    return results


def encode(value):
    return (json.dumps(value, sort_keys=True, indent=2) + "\n").encode()


def artifacts():
    assert sys.version_info[:3] == (3, 12, 13)
    cases = run_cases()
    baseline = encode(cases)
    assert baseline == encode(run_cases()), "repeat mismatch"
    assert baseline == encode(run_cases("human")), "actor-kind relabeling changed trace"
    for result in cases.values():
        assert result["metrics"]["closure_count"] == 1
    paths = ["pyproject.toml", "uv.lock", "docs/adr/0008-decision-provenance.md",
             "research/experiments/AE-002/tabletop.md", "research/experiments/AE-006/protocol.md",
             "research/experiments/AE-006/closure_experiment.py"]
    paths += [str(p) for p in sorted(Path("src/agent_empires/simulation").glob("*.py"))]
    manifest = {"model_version": "ae006-decision-closure-v2-evidence-reuse", "python": platform.python_version(),
                "seed": None, "rng": "none: deterministic decision profiles",
                "fixture_version": "ae002-decision-slices-v1", "fixture_source": paths[5],
                "classification": "authored structural hypotheses; no empirical calibration",
                "initial_actors": ["worker:agent:team", "owner:human:team"],
                "initial_decisions_and_world_evidence": "empty; ordered commands and holdings retained in each history",
                "controls": ["repeat canonical bytes", "worker kind human with all profiles/inputs fixed"],
                "metric_unit": "distinct (question, declared usable source root) pairs; not bits, probabilities or independent samples",
                "input_sha256": {path: sha256(Path(path).read_bytes()).hexdigest() for path in paths},
                "failed_controls": [], "architecture_acceptance": False}
    return {"closure-trace.json": encode({"schema_version": 1, "cases": cases}),
            "run-manifest.json": encode(manifest)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--output-dir", type=Path)
    mode.add_argument("--verify-against", type=Path)
    args = parser.parse_args()
    outputs = artifacts()
    if args.verify_against:
        for name, data in outputs.items():
            assert (args.verify_against / name).read_bytes() == data, f"stale evidence: {name}"
        print("PASS: five decision traces reproduced; repeat and actor-kind controls pass; evidence unchanged")
    else:
        args.output_dir.mkdir(parents=True, exist_ok=True)
        for name in outputs:
            if (args.output_dir / name).exists():
                raise FileExistsError(args.output_dir / name)
        for name, data in outputs.items():
            (args.output_dir / name).write_bytes(data)
        print("PASS: five authored decision traces recorded with repeat and actor-kind controls")


if __name__ == "__main__":
    main()
